// Write cordis.local.yml: a temporary Harness overlay that loads this checkout
// (absolute path) and selects the DeepSeek account model, without editing any profile.
//   node scripts/overlay.mjs && dsh --profile web --patch "$PWD/cordis.local.yml"
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
writeFileSync(
  join(root, 'cordis.local.yml'),
  `# Generated by scripts/overlay.mjs — machine-specific, not committed.
- id: agent-default-model
  config:
    provider: deepseek-account
    model: deepseek-flash
    reasoningEffort: "off"
- insert:
    - id: pathfinder-lab
      name: ${JSON.stringify(join(root, 'dist', 'host.js'))}
`,
)
console.log(`wrote ${join(root, 'cordis.local.yml')}`)
